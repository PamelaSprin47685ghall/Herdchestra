(ns hc.server.browser.port
  "The managed-browser driver port.

  The service layer never talks to Chrome directly.  It asks one
  `BrowserPort` for navigation, observation, inspection and actions.  A real
  adapter lives in `hc.server.browser.cdp`; tests use a deterministic fake.

  Port methods return plain maps.  Expected browser failures are values, not
  exceptions:

    {:status :ok ...}
    {:status :failed :error {:code ... :message ...}}
    {:status :outcome-unknown :error {...}}

  `:outcome-unknown` means an external effect may have happened.  The
  service never retries it automatically.

  A port is scoped to one browser endpoint.  `open-tab!` and `close-tab!`
  manage pages inside that endpoint.  `close!` releases the port's own
  connections and, only when the port launched the process, stops that
  process.  A port connected to an operator's shared browser never closes
  that browser.")

(defprotocol BrowserPort
  (open-tab!
    [port opts]
    "Open a page and return
    {:status :ok :tab-id ... :target-id ... :url ... :title ...}.
    OPTS may contain `:url`, but the service normally opens `about:blank`
    first and calls `navigate!` explicitly.")

  (close-tab!
    [port tab-id]
    "Close one page.  Return {:status :ok} or a structured failure.  Closing a
    page never stops the service or erases its page cards.")

  (navigate!
    [port tab-id url]
    "Navigate the tab.  Return
    {:status :ok :url ... :title ... :document-id ... :http-status ...}
    or a structured failure.  `:page-error` classifies an HTTP error page
    without pretending navigation failed.")

  (history!
    [port tab-id direction]
    "Move through page history.  DIRECTION is :back, :forward, or :reload.")

  (page-info!
    [port tab-id]
    "Read page-level identity without choosing a target:
    {:status :ok :document-id ... :url ... :title ... :sensitive-form? bool}
    or a structured failure.  Used by targetless scroll/press.")

  (observe!
    [port tab-id opts]
    "Read the current top document.  Return
    {:status :ok :url ... :title ... :document-id ... :text ... :nodes [...]
     :login-form? bool :iframes int ...}.
    A node describes one interactive element.  It never contains a field's
    value.")

  (inspect!
    [port tab-id target]
    "Re-read the current document and resolve TARGET immediately before an
    action.  Return
    {:status :ok :document-id ... :target {...} :sensitive-form? bool}
    or {:status :failed :error {:code :stale-target ...}}.  The adapter must
    resolve semantic references against the current DOM, never a cached
    coordinate.")

  (act!
    [port tab-id action]
    "Perform one action.  ACTION is
    {:kind :click|:type|:scroll|:press|:submit :target {...} :text ...}.
    Return {:status :ok :document-id ... :navigated? bool ...},
    {:status :failed ...}, or {:status :outcome-unknown ...} when the
    effect may have been delivered.")

  (screenshot!
    [port tab-id]
    "Capture the current viewport as PNG bytes:
    {:status :ok :bytes byte[] :mime-type \"image/png\"}.")

  (tab-status
    [port tab-id]
    "Return {:status :open ...} or {:status :closed}.")

  (subscribe-operator-input!
    [port handler]
    "Register one handler for trusted human input detected inside a
    controlled page.  HANDLER receives
    {:tab-id ... :kind :pointerdown|:keydown|:input|:click|:wheel}.
    The adapter must suppress events generated by its own `act!` calls.
    Returns {:ok? true :unsubscribe f} only when the adapter can guarantee
    isolated-world detection for every page it will open.  Any unavailable
    binding, isolated world or hook must return {:ok? false :error ...} or
    throw; the service then refuses agent actions instead of claiming the
    page is protected.  This is an observation of the page, not a command;
    the service decides how to pause.")

  (close!
    [port]
    "Release connections.  Stop the process only when this port launched it."))
