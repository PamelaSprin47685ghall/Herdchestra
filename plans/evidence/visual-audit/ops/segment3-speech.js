const { chromium } = require('playwright');
const fs = require('fs');
const DIR = '/tmp/hc-visual-ops/evidence';
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--disable-dev-shm-usage','--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: 'light' });
  const errors = [];
  page.on('console', m => { if (m.type() === 'error') errors.push('CONSOLE ' + m.text()); });
  page.on('pageerror', e => errors.push('PAGEERROR ' + e.message));
  await page.goto(process.env.BASE_URL + '/#/settings', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1800);
  const scroll = (y) => page.evaluate((y) => { const c = document.querySelector('.wb-content'); if (c) c.scrollTop = y; }, y);
  const shot = async (name) => { await page.screenshot({ path: `${DIR}/${name}.png` }); console.log('SHOT', name); };
  const click = async (sel, name) => { try { await page.locator(sel).filter({hasText:name}).first().evaluate(el => el.click()); } catch(e) { errors.push('CLICKFAIL '+name); } await page.waitForTimeout(800); };
  const fillLabel = async (label, value) => { const input = page.locator('label').filter({hasText:label}).locator('input').first(); await input.fill(value); };
  await click('button', '语音与朗读'); await scroll(0); await shot('s3-01-speech-empty');
  await click('button', '添加服务'); await page.waitForTimeout(300); await scroll(0); await shot('s3-02-speech-add-form');
  await fillLabel('ID', 'local-whisper');
  await fillLabel('显示名', '本地转写');
  await fillLabel('端点', 'http://127.0.0.1:9/v1');
  await fillLabel('模型', 'whisper-1');
  await page.waitForTimeout(300); await shot('s3-03-speech-form-filled');
  await click('button', '保存');
  await page.waitForTimeout(1200); await scroll(0); await shot('s3-04-speech-saved');
  await click('button', '测试');
  await page.waitForTimeout(2500); await scroll(0); await shot('s3-05-speech-test-result');
  await click('.wb-tab', '朗读'); await page.waitForTimeout(500); await shot('s3-06-tts');
  await click('.wb-tab', '翻译'); await page.waitForTimeout(500); await shot('s3-07-translation-settings');
  await page.setViewportSize({width:360,height:800}); await page.waitForTimeout(500);
  await click('.wb-tab', '语音输入'); await page.waitForTimeout(300); await scroll(0); await shot('s3-08-speech-360');
  await page.evaluate(() => { document.documentElement.dataset.theme='dark'; });
  await page.waitForTimeout(400); await scroll(0); await shot('s3-09-speech-dark-explicit');
  await click('button', '独立翻译'); await page.waitForTimeout(500); await scroll(0); await shot('s3-10-translation-dark');
  fs.writeFileSync(`${DIR}/s3-console.txt`, errors.join('\n'));
  console.log('ERRORS', errors.join(' | '));
  await browser.close();
})();
