const { chromium } = require('playwright');
const fs = require('fs');
const DIR = '/tmp/hc-visual-ops/evidence';
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--disable-dev-shm-usage','--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: 'light' });
  const errors = [];
  page.on('console', m => { if (m.type() === 'error') errors.push('CONSOLE ' + m.text()); });
  page.on('pageerror', e => errors.push('PAGEERROR ' + e.message));
  await page.goto(process.env.BASE_URL + '/#/settings', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1800);
  const scroll = (y) => page.evaluate((y) => { const c = document.querySelector('.wb-content'); if (c) c.scrollTop = y; }, y);
  const scrollTo = async (sel) => { await page.locator(sel).first().evaluate(el => el.scrollIntoView({block:'start'})); await page.waitForTimeout(250); };
  const shot = async (name) => { await page.screenshot({ path: `${DIR}/${name}.png` }); console.log('SHOT', name); };
  const click = async (sel, name) => { try { await page.locator(sel).filter({hasText:name}).first().evaluate(el => el.click()); } catch(e) { errors.push('CLICKFAIL '+name); } await page.waitForTimeout(800); };
  const fillLabel = async (label, value) => { const input = page.locator('label').filter({hasText:label}).locator('input').first(); await input.fill(value); };
  await click('button', '数据中心');
  await click('.hc-backup-tab', '创建备份');
  await scrollTo('.hc-backup'); await shot('s2-01-create-top');
  await scrollTo('.hc-backup-categories'); await shot('s2-02-create-categories');
  await scrollTo('.hc-backup-password'); await shot('s2-03-create-password');
  await page.locator('input[aria-label="备份密码"]').fill('correct horse battery staple');
  await page.locator('input[aria-label="再次输入备份密码"]').fill('correct horse battery staple');
  await page.waitForTimeout(400); await shot('s2-04-create-ready');
  await click('button', '生成加密备份');
  await page.waitForTimeout(1200);
  try { await page.getByText('最近一次备份').first().waitFor({ timeout: 60000 }); } catch(e) { errors.push('CREATE_TIMEOUT'); }
  await scrollTo('.hc-backup-result'); await shot('s2-05-create-result');
  await click('.hc-backup-tab', '恢复与预览');
  await scrollTo('.hc-backup'); await shot('s2-06-restore-top');
  await click('button', '选择这份备份');
  await page.waitForTimeout(400); await shot('s2-07-restore-selected');
  await page.locator('input[aria-label="恢复用备份密码"]').fill('correct horse battery staple');
  await click('button', '校验备份');
  await page.waitForTimeout(1200); await shot('s2-08-restore-verified');
  await click('button', '校验并生成预览');
  await page.waitForTimeout(1500);
  try { await page.getByText('恢复预览').first().waitFor({ timeout: 60000 }); } catch(e) { errors.push('PREVIEW_TIMEOUT'); }
  await scrollTo('.hc-backup-preview'); await shot('s2-09-restore-preview');
  await page.setViewportSize({width:360,height:800}); await page.waitForTimeout(500);
  await click('.hc-backup-tab', '创建备份'); await scrollTo('.hc-backup'); await shot('s2-10-create-360');
  await page.evaluate(() => { document.documentElement.dataset.theme='dark'; });
  await page.waitForTimeout(400); await scrollTo('.hc-backup'); await shot('s2-11-create-dark-explicit');
  fs.writeFileSync(`${DIR}/s2-console.txt`, errors.join('\n'));
  console.log('ERRORS', errors.join(' | '));
  await browser.close();
})();
