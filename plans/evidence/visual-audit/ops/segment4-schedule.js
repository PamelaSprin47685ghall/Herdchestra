const { chromium } = require('playwright');
const fs = require('fs');
const DIR = '/tmp/hc-visual-ops/evidence';
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--disable-dev-shm-usage','--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: 'light' });
  const errors = [];
  page.on('console', m => { if (m.type() === 'error') errors.push('CONSOLE ' + m.text()); });
  page.on('pageerror', e => errors.push('PAGEERROR ' + e.message));
  await page.goto(process.env.BASE_URL + '/#/settings', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1800);
  const scroll = (y) => page.evaluate((y) => { const c = document.querySelector('.wb-content'); if (c) c.scrollTop = y; }, y);
  const shot = async (name) => { await page.screenshot({ path: `${DIR}/${name}.png` }); console.log('SHOT', name); };
  const click = async (sel, name) => { try { await page.locator(sel).filter({hasText:name}).first().evaluate(el => el.click()); } catch(e) { errors.push('CLICKFAIL '+name); } await page.waitForTimeout(800); };
  const fillLabel = async (label, value) => { const input = page.locator('label').filter({hasText:label}).locator('input, textarea, select').first(); await input.fill(value); };
  await click('button', '定时任务'); await scroll(0); await shot('s4-01-schedule-empty');
  await click('button', '新建任务'); await page.waitForTimeout(400); await scroll(0); await shot('s4-02-form-top');
  await fillLabel('名称', '每日摘要');
  await fillLabel('提示词', '生成一份简短的每日摘要，列出今天完成的事项和待办。');
  await scroll(700); await shot('s4-03-form-mid');
  await scroll(1400); await shot('s4-04-form-preview');
  await page.locator('label').filter({hasText:'重复规则'}).locator('select').selectOption({label:'每周自选日期'});
  await page.waitForTimeout(500); await shot('s4-05-form-weekly');
  await page.locator('label').filter({hasText:/^时区/}).locator('select').selectOption({label:'固定时区'});
  await page.waitForTimeout(400);
  await page.locator('input[placeholder="Asia/Shanghai"]').fill('Not/AZone');
  await page.waitForTimeout(500); await shot('s4-06-form-zone-error');
  await page.locator('input[placeholder="Asia/Shanghai"]').fill('Asia/Shanghai');
  await page.waitForTimeout(300);
  await click('button', '保存为暂停');
  await page.waitForTimeout(1500); await scroll(0); await shot('s4-07-schedule-saved');
  await click('button', '详情'); await page.waitForTimeout(600); await scroll(0); await shot('s4-08-schedule-detail');
  await page.setViewportSize({width:360,height:800}); await page.waitForTimeout(500);
  await scroll(0); await shot('s4-09-schedule-360');
  await page.evaluate(() => { document.documentElement.dataset.theme='dark'; });
  await page.waitForTimeout(400); await shot('s4-10-schedule-dark');
  fs.writeFileSync(`${DIR}/s4-console.txt`, errors.join('\n'));
  console.log('ERRORS', errors.join(' | '));
  await browser.close();
})();
