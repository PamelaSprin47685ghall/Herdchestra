#!/usr/bin/env bash
# Build and run the generated-card jsdom interaction smoke.
#
# This is a focused Node harness; the production build is shadow-cljs :app.
# It installs jsdom before React/ReactDOM load, then exercises local save,
# invalid/valid send, chart filtering/reset, table toggling, and a fetch guard.
set -euo pipefail

cd "$(dirname "$0")/../.."
OUT="$(mktemp -d "./out-generated-card-dom.XXXXXX")"
OUT="${OUT#./}"
cleanup() {
  local status=$?
  if [ "$status" -eq 0 ]; then
    rm -rf "$OUT"
  else
    printf 'generated-card dom output kept for inspection: %s\n' "$OUT" >&2
  fi
  exit "$status"
}
trap cleanup EXIT

clojure -Sdeps '{:deps {org.clojure/clojurescript {:mvn/version "1.12.145"}}}' \
  -M:dev:client \
  -m cljs.main \
  -co "$(cat <<EDN
{:target :nodejs
 :output-to "$OUT/test.js"
 :output-dir "$OUT"
 :optimizations :none
 :main hc.client.generated-card.dom-test/-main
 :language-in :ecmascript-2017
 :rewrite-polyfills false
 :npm-deps false
 :foreign-libs
 [{:file "test/js/react_shim.js"
   :provides ["react"]
   :module-type :commonjs}
  {:file "test/js/react_dom_shim.js"
   :provides ["react-dom"]
   :module-type :commonjs}
  {:file "test/js/react_dom_server_shim.js"
   :provides ["react-dom/server"]
   :module-type :commonjs}
  {:file "test/js/f7_global_shim.js"
   :provides ["framework7-react"]
   :module-type :commonjs}]}
EDN
)" \
  -c hc.client.generated-card.dom-test

node test/js/run_generated_card_dom_tests.cjs "$OUT"
